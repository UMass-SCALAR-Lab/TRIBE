"""
BAAI/TACO eval (pass@1 greedy by default, or pass@k with --num_generations/--temperature) for a single
checkpoint, via vLLM. Mirrors scripts/eval_kodcode.py's structure/protocol (generate code, execute it
against hidden tests in an isolated subprocess with a timeout); see that module's docstring for the
rationale.

TACO's own `datasets` loading script (`TACO.py`) is unloadable by either `datasets` version available in
this project's envs: the old `llm_gen` one (2.20.0) crashes inspecting the repo's parquet-export metadata
(`UnicodeDecodeError` on a gzip-magic byte) before even reaching the script, and the new `llm_gen_new` one
(5.x) dropped script-based dataset support entirely. Bypassing `datasets` for this one: the repo also ships
a plain `ALL/test-00000-of-00001.parquet` file (auto-generated by HF, same rows the script would yield for
the "ALL" config's test split), fetched directly via `huggingface_hub.hf_hub_download` + `pandas.read_parquet`.

TACO is APPS-style: most rows (~95%) are "stdio" problems — the model's program reads from stdin and writes
to stdout, checked by feeding each test case's stdin to a subprocess and exact-matching stdout (trailing
whitespace on each line ignored). The rest are "functional" problems (`input_output` JSON has a `fn_name`
key, `starter_code` gives the function signature to complete) — checked by exec'ing the generated code and
calling `fn_name` directly, comparing the return value's `repr` to each expected output. A problem is scored
correct only if ALL of its test cases pass (matching TACO/APPS's own "strict-accuracy" scoring), capped at
--max_test_cases per problem (some problems have hundreds; running all of them per generation is not
worth the wall-clock for a base-performance check).

Usage:
python scripts/eval_taco.py \
    --model_path Qwen/Qwen2.5-3B-Instruct \
    --name base \
    --limit 200 \
    --output_file taco_eval/base.json
"""

import argparse
import json
import re
import subprocess
import sys
import tempfile
from pathlib import Path

import pandas as pd
from huggingface_hub import hf_hub_download
from vllm import LLM, SamplingParams


CODE_BLOCK_RE = re.compile(r"```(?:python)?\s*\n(.*?)```", re.DOTALL)

STDIO_SYSTEM_PROMPT = (
    "You are an expert competitive programmer. Write a complete Python program that reads input from "
    "stdin and writes the answer to stdout, solving the given problem. Return ONLY a single ```python "
    "code block containing the full program — no explanation."
)
FUNCTIONAL_SYSTEM_PROMPT = (
    "You are an expert Python programmer. Complete the given function so it solves the problem. Return "
    "ONLY a single ```python code block containing the full function definition (and any needed imports) "
    "— no explanation."
)


def load_taco_test_split() -> pd.DataFrame:
    path = hf_hub_download("BAAI/TACO", "ALL/test-00000-of-00001.parquet", repo_type="dataset")
    return pd.read_parquet(path)


def extract_code(completion_text: str) -> str:
    # Last block, not first: reasoning models (e.g. Qwen3's default thinking mode) can emit code inside
    # <think>...</think> before the actual final answer's code block.
    matches = CODE_BLOCK_RE.findall(completion_text)
    return matches[-1] if matches else completion_text


def build_prompt(row) -> tuple[str, str]:
    """Returns (system_prompt, user_prompt)."""
    io = json.loads(row["input_output"])
    if "fn_name" in io:
        prompt = f"{row['question']}\n\nComplete this function:\n```python\n{row['starter_code']}\n```"
        return FUNCTIONAL_SYSTEM_PROMPT, prompt
    return STDIO_SYSTEM_PROMPT, row["question"]


def _as_text(value) -> str:
    # Some TACO rows give a stdin/stdout blob as a single string, others as a list of lines (e.g.
    # multiple whitespace-separated test cases packed into one problem) — normalize both to one string.
    return value if isinstance(value, str) else "\n".join(value)


def run_stdio_tests(code: str, io: dict, max_test_cases: int, exec_timeout: float) -> bool:
    inputs = io["inputs"][:max_test_cases]
    outputs = io["outputs"][:max_test_cases]
    with tempfile.TemporaryDirectory() as tmpdir:
        script_path = Path(tmpdir) / "solution.py"
        script_path.write_text(code)
        for raw_stdin, raw_expected in zip(inputs, outputs, strict=True):
            stdin, expected = _as_text(raw_stdin), _as_text(raw_expected)
            try:
                result = subprocess.run(
                    [sys.executable, str(script_path)],
                    input=stdin,
                    capture_output=True,
                    text=True,
                    timeout=exec_timeout,
                )
            except subprocess.TimeoutExpired:
                return False
            got_lines = [line.rstrip() for line in result.stdout.splitlines()]
            expected_lines = [line.rstrip() for line in expected.splitlines()]
            if got_lines != expected_lines:
                return False
    return True


def run_functional_tests(code: str, fn_name: str, io: dict, max_test_cases: int, exec_timeout: float) -> bool:
    inputs = io["inputs"][:max_test_cases]
    outputs = io["outputs"][:max_test_cases]
    harness = (
        code
        + "\n\nimport json, sys\n"
        + f"_fn = {fn_name}\n"
        + "_args = json.loads(sys.argv[1])\n"
        + "print(json.dumps(_fn(*_args)))\n"
    )
    with tempfile.TemporaryDirectory() as tmpdir:
        script_path = Path(tmpdir) / "solution.py"
        script_path.write_text(harness)
        for args, expected in zip(inputs, outputs, strict=True):
            try:
                result = subprocess.run(
                    [sys.executable, str(script_path), json.dumps(args)],
                    capture_output=True,
                    text=True,
                    timeout=exec_timeout,
                )
                got = json.loads(result.stdout.strip())
            except Exception:
                return False
            if got != expected and [got] != expected:
                return False
    return True


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--model_path", required=True, help="HF model id or local checkpoint directory.")
    parser.add_argument("--name", required=True, help="Label for this checkpoint in the output JSON.")
    parser.add_argument("--max_new_tokens", type=int, default=1024)
    parser.add_argument("--output_file", required=True)
    parser.add_argument(
        "--limit", type=int, default=200, help="Number of examples to evaluate (random subsample of `test`)."
    )
    parser.add_argument("--seed", type=int, default=0, help="Shuffle seed for the --limit subsample.")
    parser.add_argument("--num_generations", type=int, default=1, help="k for pass@k. Defaults to 1 (greedy pass@1).")
    parser.add_argument("--temperature", type=float, default=0.0, help="Must be > 0 when --num_generations > 1.")
    parser.add_argument("--top_k", type=int, default=-1)
    parser.add_argument(
        "--max_test_cases", type=int, default=10, help="Cap on test cases run per problem (some have hundreds)."
    )
    parser.add_argument(
        "--exec_timeout", type=float, default=6.0, help="Wall-clock timeout (seconds) per test-case execution."
    )
    args = parser.parse_args()

    df = load_taco_test_split()
    df = df.sample(n=min(args.limit, len(df)), random_state=args.seed).reset_index(drop=True)

    llm = LLM(model=args.model_path, dtype="bfloat16")
    tokenizer = llm.get_tokenizer()
    if tokenizer.chat_template is None:
        chat_template_path = Path(args.model_path) / "chat_template.jinja"
        if chat_template_path.exists():
            tokenizer.chat_template = chat_template_path.read_text()

    prompts = []
    for _, row in df.iterrows():
        system_prompt, user_prompt = build_prompt(row)
        prompts.append(
            tokenizer.apply_chat_template(
                [{"role": "system", "content": system_prompt}, {"role": "user", "content": user_prompt}],
                tokenize=False,
                add_generation_prompt=True,
            )
        )

    sampling_params = SamplingParams(
        n=args.num_generations, temperature=args.temperature, top_k=args.top_k, max_tokens=args.max_new_tokens
    )
    outputs = llm.generate(prompts, sampling_params)

    num_correct = 0
    per_example = []
    for output, (_, row) in zip(outputs, df.iterrows(), strict=True):
        io = json.loads(row["input_output"])
        samples = output.outputs
        results = []
        for o in samples:
            code = extract_code(o.text)
            if "fn_name" in io:
                results.append(run_functional_tests(code, io["fn_name"], io, args.max_test_cases, args.exec_timeout))
            else:
                results.append(run_stdio_tests(code, io, args.max_test_cases, args.exec_timeout))
        correct = any(results)
        num_correct += int(correct)
        per_example.append({
            "name": row["name"],
            "difficulty": row["difficulty"],
            "style": "functional" if "fn_name" in io else "stdio",
            "correct": correct,
        })

    result = {
        "name": args.name,
        "model_path": args.model_path,
        "dataset": "BAAI/TACO",
        "split": f"test (random {len(df)}-example subsample, seed={args.seed})",
        "num_generations": args.num_generations,
        "max_test_cases": args.max_test_cases,
        "num_correct": num_correct,
        "num_total": len(df),
        "accuracy": num_correct / len(df),
        "per_example": per_example,
    }
    print(json.dumps({k: v for k, v in result.items() if k != "per_example"}, indent=2))

    output_path = Path(args.output_file)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(json.dumps(result, indent=2))
